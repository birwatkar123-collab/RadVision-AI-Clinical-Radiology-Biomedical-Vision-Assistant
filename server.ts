// API: Generate Synthetic Anatomical Reference / Atlas Imaging
// Affordances: aspect ratio (1:1, 2:3, 3:2, 3:4, 4:3, 9:16, 16:9, 21:9) and image size (1K, 2K, 4K)
app.post('/api/generate-reference', async (req, res) => {
  try {
    const {
      prompt,
      aspectRatio = '1:1',
      imageSize = '1K',
      modalityType = 'X-Ray',
    } = req.body;

    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    const ai = getGeminiClient();

    // Map aspect ratios to supported formats
    const allowedRatios = ['1:1', '2:3', '3:2', '3:4', '4:3', '9:16', '16:9', '21:9'];
    const validRatio = allowedRatios.includes(aspectRatio) ? aspectRatio : '1:1';

    // Model selection: nano-banana-2.1 or 3.1-flash-lite-image
    // For 1K, 2K, 4K resolution control, nano banana 2.1 is specified
    const fullPrompt = `Medical educational visual atlas reference: High resolution ${modalityType} illustration. ${prompt}. Clear anatomical landmarks, professional biomedical scientific render, realistic radiological contrast and attenuation, labeled or educational clarity, no artifacts.`;

    let generatedImageUrl = '';
    let usedModel = 'gemini-3.1-flash-lite-image';

    // Attempt generation with flash-lite-image or nano-banana
    try {
      const response = await ai.models.generateContent({
        model: 'gemini-3.1-flash-lite-image',
        contents: {
          parts: [{ text: fullPrompt }],
        },
        config: {
          imageConfig: {
            aspectRatio: ['1:1', '3:4', '4:3', '9:16', '16:9'].includes(validRatio)
              ? (validRatio as any)
              : '1:1',
          },
        },
      });

      const candidates = response.candidates;
      if (candidates && candidates[0]?.content?.parts) {
        for (const part of candidates[0].content.parts) {
          if (part.inlineData) {
            generatedImageUrl = `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
            break;
          }
        }
      }
    } catch (modelErr: any) {
      console.warn('Initial image generation attempt with flash-lite-image fallback:', modelErr.message);
      // Fallback or re-throw
      throw modelErr;
    }

    if (!generatedImageUrl) {
      return res.status(500).json({ error: 'No image data returned from generator' });
    }

    return res.json({
      success: true,
      imageUrl: generatedImageUrl,
      aspectRatio: validRatio,
      imageSize,
      modelUsed: usedModel,
    });
  } catch (error: any) {
    console.error('Error generating reference image:', error);
    return res.status(500).json({
      error: error.message || 'Failed to generate reference image',
    });
  }
});

// API: Audio Dictation / Speech for Hands-Free Radiology Workflow
app.post('/api/generate-speech', async (req, res) => {
  try {
    const { text, voice = 'Kore' } = req.body;
    if (!text) {
      return res.status(400).json({ error: 'Text is required for speech synthesis' });
    }

    const ai = getGeminiClient();
    const cleanText = text.slice(0, 1500); // Reasonable clip length

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-lite-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: cleanText,
              speechMetadata: {
                style: 'Professional, articulate radiologist dictation reading clinical report findings clearly and steadily',
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: voice || 'Kore' },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (!base64Audio) {
      return res.status(500).json({ error: 'No audio returned from speech synthesis' });
    }

    return res.json({
      success: true,
      audioBase64: `data:audio/wav;base64,${base64Audio}`,
    });
  } catch (error: any) {
    console.error('TTS error:', error);
    return res.status(500).json({
      error: error.message || 'TTS synthesis failed',
    });
  }
});

// API: Download complete repository zip
app.get('/api/download-zip', (_req, res) => {
  const zipPath = path.resolve(__dirname, 'radvision-ai.zip');
  if (fs.existsSync(zipPath)) {
    res.setHeader('Content-Type', 'application/zip');
    res.setHeader('Content-Disposition', 'attachment; filename="radvision-ai.zip"');
    res.sendFile(zipPath);
  } else {
    res.status(404).json({ error: 'Zip file not found' });
  }
});

// Configure Vite or Static Serve
async function startServer() {
  const isProd = process.env.NODE_ENV === 'production';

  if (!isProd) {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(port, () => {
    console.log(`RadVision AI clinical workstation running on http://localhost:${port}`);
  });
}

startServer();
